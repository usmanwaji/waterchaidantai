"""Open an existing .docx (from anywhere), enforce Thai, and save a copy."""
import os
import tempfile

from docx import Document

from .enforce import enforce_thai, DEFAULT_THAI_FONT


def enforce_thai_file(
    in_path,
    out_path,
    *,
    force=False,
    thai_font=DEFAULT_THAI_FONT,
    thai_digits=False,
    insert_breaks=False,
    fix_spacing=False,
    overwrite=False,
):
    """Ingest *any* .docx, enforce Thai complex-script props, write to out_path.

    Works on documents that were not generated by this library — e.g. files a
    client produced in Word — because it operates purely on the OOXML.

    ``overwrite`` (default ``False``) guards a client's existing file: if
    ``out_path`` already exists we raise ``FileExistsError`` rather than
    clobbering it silently. Pass ``overwrite=True`` to allow replacing it.

    In-place enforcement (``in_path == out_path``) is always allowed regardless
    of ``overwrite`` — that's the explicit intent — but the result is written to
    a temp file first and swapped in atomically via ``os.replace`` so a crash
    mid-processing can never leave the original truncated/corrupt.
    """
    in_abs = os.path.abspath(in_path)
    out_abs = os.path.abspath(out_path)
    in_place = in_abs == out_abs

    if not in_place and os.path.exists(out_path) and not overwrite:
        raise FileExistsError(
            f"refusing to overwrite existing file {out_path!r}; "
            f"pass overwrite=True to replace it"
        )

    doc = Document(in_path)
    enforce_thai(
        doc,
        force=force,
        thai_font=thai_font,
        thai_digits=thai_digits,
        insert_breaks=insert_breaks,
    )
    if fix_spacing:
        from .layout import fix_line_spacing
        fix_line_spacing(doc)

    if in_place:
        # Write to a sibling temp file then atomically swap it over the original,
        # so the source is never partially overwritten if we crash mid-save.
        out_dir = os.path.dirname(out_abs) or "."
        fd, tmp_path = tempfile.mkstemp(suffix=".docx", dir=out_dir)
        os.close(fd)
        try:
            doc.save(tmp_path)
            os.replace(tmp_path, out_abs)
        except BaseException:
            if os.path.exists(tmp_path):
                os.remove(tmp_path)
            raise
    else:
        doc.save(out_path)
    return out_path
